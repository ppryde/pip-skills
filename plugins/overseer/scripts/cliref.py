"""One-line verb signatures, derived from the argparse parser (WF-265 PR B).

The orchestrate skill inlines a block of these and ``references/cli.md`` lists all of
them; both are generated by ``gen_cli_ref.py`` from this module, and a test fails when
either drifts. ``cli.py help [verb]`` prints the same lines, so a ``--help`` probe costs
one line instead of argparse's page. Output is deterministic: verbs sorted, no timestamps.
"""
from __future__ import annotations

import argparse


def _verbs(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def _value(action: argparse.Action) -> str:
    if action.choices and len(action.choices) <= 5:
        return "|".join(str(c) for c in action.choices)
    return action.metavar or f"<{action.dest.replace('_', '-')}>"


def _flag(action: argparse.Action) -> str:
    name = max(action.option_strings, key=len)
    if action.nargs == 0:  # store_true and friends
        return name
    return f"{name} {_value(action)}"


def signature(name: str, sub: argparse.ArgumentParser, hide: frozenset[str] = frozenset()) -> str:
    """``verb <pos> [--opt <val>] --required <val> (--a X | --b Y)`` for one subparser.

    ``hide`` drops optional flags by dest and ends the line with ``[...]`` so a reader knows
    ``references/cli.md`` has more; required flags are never hidden."""
    hidden = False
    grouped: dict[int, list[argparse.Action]] = {}
    in_group: dict[int, argparse._MutuallyExclusiveGroup] = {}
    for group in sub._mutually_exclusive_groups:
        for action in group._group_actions:
            grouped.setdefault(id(group), []).append(action)
            in_group[id(action)] = group
    parts: list[str] = [name]
    seen_groups: set[int] = set()
    for action in sub._actions:
        if isinstance(action, argparse._HelpAction) or action.help is argparse.SUPPRESS:
            continue
        if action.dest in hide and not action.required:
            hidden = True
            continue
        if isinstance(action, argparse._SubParsersAction):
            parts.append("|".join(action.choices))
            continue
        group = in_group.get(id(action))
        if group is not None:
            if id(group) in seen_groups:
                continue
            seen_groups.add(id(group))
            members = [a for a in grouped[id(group)] if a.dest not in hide]
            if not members:
                hidden = True
                continue
            inner = " | ".join(_flag(a) for a in members)
            parts.append(f"({inner})" if group.required else f"[{inner}]")
            continue
        if not action.option_strings:
            token = f"<{action.dest.replace('_', '-')}>"
            if action.choices and len(action.choices) <= 5:
                token = "|".join(str(c) for c in action.choices)
            if action.nargs in ("*", "?"):
                token = f"[{token}]"
            elif action.nargs == "+":
                token = f"{token} ..."
            parts.append(token)
        elif action.required:
            parts.append(_flag(action))
        else:
            parts.append(f"[{_flag(action)}]")
    if hidden:
        parts.append("[...]")
    return " ".join(parts)


def signatures(parser: argparse.ArgumentParser) -> dict[str, str]:
    """verb -> signature, for every verb, sorted by verb."""
    return {n: signature(n, s) for n, s in sorted(_verbs(parser).items())}


def verb_help(parser: argparse.ArgumentParser) -> dict[str, str]:
    return {
        a.dest: (a.help or "")
        for act in parser._actions if isinstance(act, argparse._SubParsersAction)
        for a in act._choices_actions
    }
