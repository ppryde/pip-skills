#!/usr/bin/env python3
"""Regenerate the CLI signature block in the orchestrate skill and ``references/cli.md``.

    python3 scripts/gen_cli_ref.py            # rewrite both
    python3 scripts/gen_cli_ref.py --check    # exit 1 if either is out of date

Signatures come from the argparse parser (``scripts.cliref``), so the skill cannot drift
from the CLI; a test runs ``--check``. Output is deterministic: sorted, no timestamps.
"""
from __future__ import annotations

import sys
from pathlib import Path

PLUGIN = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PLUGIN))

from scripts.cli import build_parser  # noqa: E402
from scripts.cliref import _verbs, signature, signatures, verb_help  # noqa: E402

SKILL = PLUGIN / "skills" / "orchestrate" / "SKILL.md"
REF = PLUGIN / "skills" / "orchestrate" / "references" / "cli.md"
BEGIN, END = "<!-- cli:begin -->", "<!-- cli:end -->"

# Verbs an S/M card needs, inlined in SKILL.md in this order. Everything else lives in cli.md.
INLINE = (
    "resume", "bootstrap", "dispatch-prep", "set-stage", "set-section", "set-field", "show",
    "block", "unblock", "park", "unpark", "done", "abandon", "release", "depends",
    "facts", "accept-fact", "reject-fact", "conflicts", "handoff", "handover", "vigil",
    "usage", "help",
)
# Rarely-used optional flags left out of the inline lines (they end in `[...]`); cli.md has all.
ELIDE = {
    "bootstrap": {"jira", "linear", "type", "slug", "labels", "goal", "force_gate"},
    "set-field": {"order", "repo", "sprint", "body", "touches", "labels", "priority", "estimate"},
    "dispatch-prep": {"force_gate"},
    "set-stage": {"force_gate"},
    "facts": {"tag", "stale", "json"},
    "show": {"json"},
}
# Verbs that are hook backends, never typed by a model.
HOOK_BACKENDS = {
    "report-hook", "pretool-hook", "checklist-sync-hook", "claim-stop-hook",
    "claim-prompt-hook", "dashboard-refresh-hook", "claim-nudged",
}


def inline_block() -> str:
    verbs = _verbs(build_parser())
    missing = [v for v in INLINE if v not in verbs]
    if missing:
        raise SystemExit(f"gen_cli_ref: INLINE names verbs the parser lacks: {missing}")
    return "\n".join(signature(v, verbs[v], frozenset(ELIDE.get(v, ()))) for v in INLINE)


def reference() -> str:
    sigs = signatures(build_parser())
    helps = verb_help(build_parser())
    lines = [
        "# CLI reference (generated)",
        "",
        "Generated by `scripts/gen_cli_ref.py` from the argparse parser. Do not edit by hand:",
        "a test fails when this file or the block in `SKILL.md` drifts. `<card-id>` is a card id",
        "(`WF-123`). The parser rejects anything else with `error: ...`, exit 1; exit 2 is the guard,",
        "exit 3 a `GATE:` refusal (`gates.md`). `help <verb>` prints one verb's line.",
        "",
        "## Verbs",
        "",
        "```",
    ]
    lines += [sigs[v] for v in sigs if v not in HOOK_BACKENDS]
    lines += ["```", "", "## Hook backends (never typed by hand)", "", "```"]
    lines += [sigs[v] for v in sorted(HOOK_BACKENDS) if v in sigs]
    lines += ["```", ""]
    described = {v: h for v, h in helps.items() if h}
    if described:
        lines += ["## Verbs with a description", ""]
        lines += [f"- `{v}`: {h}" for v, h in sorted(described.items())]
        lines.append("")
    return "\n".join(lines)


def render_skill(text: str) -> str:
    head, sep, rest = text.partition(BEGIN)
    _, sep2, tail = rest.partition(END)
    if not sep or not sep2:
        raise SystemExit(f"gen_cli_ref: {SKILL} lacks the {BEGIN} ... {END} markers")
    return f"{head}{BEGIN}\n```\n{inline_block()}\n```\n{END}{tail}"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    new_skill = render_skill(SKILL.read_text())
    new_ref = reference()
    stale = [p.name for p, new in ((SKILL, new_skill), (REF, new_ref))
             if not p.exists() or p.read_text() != new]
    if check:
        if stale:
            print(f"out of date: {', '.join(stale)}; run scripts/gen_cli_ref.py", file=sys.stderr)
            return 1
        return 0
    SKILL.write_text(new_skill)
    REF.write_text(new_ref)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
