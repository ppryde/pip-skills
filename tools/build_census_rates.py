#!/usr/bin/env python3
"""Generate census-mod's price table (plugin/core/rates.ts) from chronicle's pricing.py.

census-mod is standalone, so it carries its own copy of the rates; this keeps that copy
identical to chronicle's seed table. `--check` exits 1 when the committed file has drifted
(tests/census/test_census_mod_bundle.py runs it); plugins/census-mod/sync-bundle.sh runs
the generator.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
SOURCE = REPO / "plugins" / "chronicle" / "scripts" / "pricing.py"
TARGET = REPO / "plugins" / "census-mod" / "plugin" / "core" / "rates.ts"


def _pricing() -> Any:
    spec = importlib.util.spec_from_file_location("chronicle_pricing", SOURCE)
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render() -> str:
    p = _pricing()
    rates: dict[str, dict[str, float]] = p._RATES
    rows = "\n".join(f"  {json.dumps(k)}: {json.dumps(v)}," for k, v in rates.items())
    return (
        "// GENERATED by tools/build_census_rates.py from plugins/chronicle/scripts/pricing.py: do not edit.\n"
        "// Run plugins/census-mod/sync-bundle.sh after a chronicle price change.\n"
        "// USD per million tokens; a model missing here is unpriced, never guessed.\n"
        "export type Rates = { input: number; output: number; cache_read: number; cache_write_5m?: number; cache_write_1h?: number }\n"
        f"export const PRICING_AS_OF = {json.dumps(p.PRICING_AS_OF)}\n"
        f"export const CACHE_WRITE_5M_MULTIPLIER = {p.CACHE_WRITE_5M_MULTIPLIER!r}\n"
        f"export const CACHE_WRITE_1H_MULTIPLIER = {p.CACHE_WRITE_1H_MULTIPLIER!r}\n"
        f"export const RATES: Record<string, Rates> = {{\n{rows}\n}}\n"
    )


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(
                f"{TARGET.relative_to(REPO)} is stale: run plugins/census-mod/sync-bundle.sh",
                file=sys.stderr,
            )
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
